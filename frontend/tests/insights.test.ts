async function mounted(component: Component, location = '/insights', props = {}) {
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: '/:pathMatch(.*)*', component: { template: '<div />' } }] })
  await router.push(location); await router.isReady()
  const wrapper = mount(component, { props, global: { plugins: [router] } })
  await flushPromises()
  return { wrapper, router }
}
function button(wrapper: VueWrapper, text: string) { return wrapper.findAll('button').find(item => item.text() === text)! }
function mountCard(item = insight, apply = vi.fn().mockResolvedValue(true)) { return mounted(InsightCard, '/insights', { insight: structuredClone(item), selected: false, busy: false, apply }) }

